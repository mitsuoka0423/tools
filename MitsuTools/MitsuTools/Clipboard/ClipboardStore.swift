import AppKit
import Observation

/// クリップボード履歴の 1 件。メモリ上だけに持つ。
///
/// 一覧の表示・検索・重複の確認で何度も使う値（title・searchText・fingerprint）は、
/// 作るときに一度だけ計算して持っておく。長いテキストでも、一覧や検索が重くならないようにするため。
struct ClipboardItem: Identifiable {
    enum Kind: String, CaseIterable { case text, image, file }

    let id = UUID()
    let kind: Kind
    let date: Date
    let appName: String?
    /// 元のクリップボードの内容（全形式）。貼り付け時にそのまま戻す。
    let representations: [(type: NSPasteboard.PasteboardType, data: Data)]
    let plainText: String?
    let fileURLs: [URL]
    let image: NSImage?

    /// 一覧に出す 1 行の文字列
    let title: String
    /// 検索に使う文字列。長いテキストは先頭だけ。
    let searchText: String
    /// 同じ内容かを調べる印。内容全体ではなく、長さとハッシュで比べる。
    let fingerprint: String

    /// 検索の対象にする文字数の上限（これより後ろの文字は、検索に出ない）
    static let searchCharacterLimit = 10_000

    init(kind: Kind, date: Date, appName: String?,
         representations: [(type: NSPasteboard.PasteboardType, data: Data)],
         plainText: String?, fileURLs: [URL], image: NSImage?) {
        self.kind = kind
        self.date = date
        self.appName = appName
        self.representations = representations
        self.plainText = plainText
        self.fileURLs = fileURLs
        self.image = image

        switch kind {
        case .text:
            let text = plainText ?? ""
            // 先頭の一部だけを見て 1 行にする（全文を処理しない）
            let head = text.prefix(2000).trimmingCharacters(in: .whitespacesAndNewlines)
                .replacingOccurrences(of: "\n", with: " ")
            title = head.isEmpty ? "（空白）" : String(head.prefix(200))
            searchText = String(text.prefix(Self.searchCharacterLimit))
            fingerprint = "t:" + Self.digest(text)
        case .file:
            title = fileURLs.map(\.lastPathComponent).joined(separator: ", ")
            searchText = fileURLs.map(\.path).joined(separator: " ")
            fingerprint = "f:" + fileURLs.map(\.path).joined(separator: "|")
        case .image:
            if let image {
                let rep = image.representations.first
                let w = rep?.pixelsWide ?? Int(image.size.width), h = rep?.pixelsHigh ?? Int(image.size.height)
                title = "画像 \(w)×\(h)"
            } else {
                title = "画像"
            }
            searchText = title
            fingerprint = "i:\(representations.first?.data.hashValue ?? 0)"
        }
    }

    private static func digest(_ text: String) -> String {
        var hasher = Hasher()
        hasher.combine(text)
        return "\(text.utf8.count):\(hasher.finalize())"
    }
}

/// クリップボードを監視して履歴を貯める。ディスクには一切書かない。
@MainActor
@Observable
final class ClipboardStore {
    private(set) var items: [ClipboardItem] = [] {
        didSet { revision += 1 }
    }
    /// 履歴が変わるたびに増やす。一覧の絞り込み結果を使い回してよいかの判断に使う。
    private(set) var revision = 0

    var maxCount: Int {
        didSet {
            let clamped = min(max(maxCount, 1), Self.maxCountLimit)
            if clamped != maxCount { maxCount = clamped; return }
            UserDefaults.standard.set(maxCount, forKey: Keys.maxCount)
            trim()
        }
    }
    /// 1 件あたりの大きさの上限（10 MB）
    static let maxItemBytes = 10 * 1024 * 1024
    static let defaultMaxCount = 1000
    /// メモリだけに持つので、増やしすぎないよう上限を設ける。
    static let maxCountLimit = 10_000
    var autoPaste: Bool {
        didSet { UserDefaults.standard.set(autoPaste, forKey: Keys.autoPaste) }
    }
    var skipConcealed: Bool {
        didSet { UserDefaults.standard.set(skipConcealed, forKey: Keys.skipConcealed) }
    }

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    private let pasteboard = NSPasteboard.general

    private enum Keys {
        static let maxCount = "clipboard.maxCount"
        static let autoPaste = "clipboard.autoPaste"
        static let skipConcealed = "clipboard.skipConcealed"
    }

    /// パスワード管理アプリなどが「記録しないで」と示すための型（nspasteboard.org の取り決め）。
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        let d = UserDefaults.standard
        d.register(defaults: [
            Keys.maxCount: Self.defaultMaxCount,
            Keys.autoPaste: true,
            Keys.skipConcealed: true,
        ])
        maxCount = d.integer(forKey: Keys.maxCount)
        autoPaste = d.bool(forKey: Keys.autoPaste)
        skipConcealed = d.bool(forKey: Keys.skipConcealed)
    }

    func start() {
        lastChangeCount = pasteboard.changeCount
        timer?.invalidate()
        let timer = Timer(timeInterval: 0.3, repeats: true) { _ in
            MainActor.assumeIsolated { [weak self] in self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        items.removeAll()
    }

    // MARK: 貼り付け用に書き戻す

    func write(_ item: ClipboardItem, plainTextOnly: Bool) {
        pasteboard.clearContents()
        if plainTextOnly, let text = item.plainText {
            pasteboard.setString(text, forType: .string)
        } else {
            let pbItem = NSPasteboardItem()
            var written = Set<NSPasteboard.PasteboardType>()
            for rep in item.representations where !Self.isPromiseType(rep.type) {
                if pbItem.setData(rep.data, forType: rep.type) { written.insert(rep.type) }
            }
            // 画像は、貼り付け先が読める形式（TIFF・PNG）を必ず入れる。
            // コピー元によっては JPEG や独自の形式しかなく、多くのアプリが読めないため。
            if let image = item.image ?? (item.kind == .image ? NSImage(data: item.representations.first?.data ?? Data()) : nil) {
                if !written.contains(.tiff), let tiff = image.tiffRepresentation {
                    pbItem.setData(tiff, forType: .tiff)
                }
                if !written.contains(.png), let tiff = image.tiffRepresentation,
                   let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
                    pbItem.setData(png, forType: .png)
                }
            }
            if !pasteboard.writeObjects([pbItem]) {
                NSLog("MitsuTools: クリップボードに書き戻せませんでした（\(item.kind.rawValue)）")
            }
        }
        // 自分で書いた内容は履歴に入れ直さない。ただし選んだ項目は先頭へ移す。
        lastChangeCount = pasteboard.changeCount
        if let index = items.firstIndex(where: { $0.id == item.id }) {
            items.insert(items.remove(at: index), at: 0)
        }
    }

    /// 「あとでファイルを渡す」という約束の型。コピー元のアプリがもう応じられないので、書き戻すと貼り付けが失敗する。
    private static func isPromiseType(_ type: NSPasteboard.PasteboardType) -> Bool {
        let raw = type.rawValue
        return raw.contains("promised") || raw.contains("NSPromise") || raw.contains("FilePromise")
    }

    // MARK: 監視

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard let item = capture() else { return }
        items.removeAll { $0.fingerprint == item.fingerprint }
        items.insert(item, at: 0)
        trim()
    }

    private func trim() {
        if items.count > maxCount { items.removeLast(items.count - maxCount) }
    }

    private func capture() -> ClipboardItem? {
        guard let pbItem = pasteboard.pasteboardItems?.first else { return nil }
        let types = pbItem.types
        if skipConcealed, types.contains(where: { Self.privateTypes.contains($0.rawValue) }) { return nil }

        let frontApp = NSWorkspace.shared.frontmostApplication
        // 機密情報を扱うアプリ（「一般」で設定。全機能に共通）でのコピーは記録しない
        if PrivacySettings.shared.isSensitive(frontApp?.bundleIdentifier) { return nil }

        var reps: [(NSPasteboard.PasteboardType, Data)] = []
        for type in types {
            if let data = pbItem.data(forType: type) { reps.append((type, data)) }
        }
        guard !reps.isEmpty else { return nil }

        // 巨大なコピーは、メモリを使いすぎて全体が重くなるので、上限を設ける。
        // 上限を超えたら、テキストだけ（書式なし）で残す。それも上限を超えるものは記録しない。
        if reps.reduce(0, { $0 + $1.1.count }) > Self.maxItemBytes {
            guard let text = pbItem.string(forType: .string), text.utf8.count <= Self.maxItemBytes else { return nil }
            reps = [(.string, Data(text.utf8))]
        }

        let fileURLs = (pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        let text = pbItem.string(forType: .string)
        // TIFF・PNG に限らず、JPEG や HEIC など NSImage が読める画像はすべて画像として扱う
        let image: NSImage? = NSImage.canInit(with: pasteboard) ? NSImage(pasteboard: pasteboard) : nil

        let kind: ClipboardItem.Kind
        if !fileURLs.isEmpty { kind = .file }
        else if let text, !text.isEmpty { kind = .text }
        else if image != nil { kind = .image }
        else { return nil }

        return ClipboardItem(kind: kind, date: .now, appName: frontApp?.localizedName,
                             representations: reps, plainText: text, fileURLs: fileURLs,
                             image: kind == .image ? image : nil)
    }
}
